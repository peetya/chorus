// Builds the wall's world map: public/world.svg (land) and src/zones.ts (where each time zone's dot goes).
// Run once: node scripts/world-map.ts. Both outputs are committed, so the app needs neither source at runtime.
//
// Land: Natural Earth 1:110m (public domain). Places: the tz database's zone.tab (public domain), the
// coordinates of each zone's main city.
//
// The map is plain longitude and latitude (x = longitude + 180, y = 84 - latitude), cut at 84° N and
// 60° S, so it's 360 by 144. Antarctica is left out.
import { readFileSync, writeFileSync } from "node:fs";

const LAND =
  "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson";
const ZONES = "/usr/share/zoneinfo/zone.tab";

const x = (lon: number) => Math.round((lon + 180) * 10) / 10;
const y = (lat: number) => Math.round((84 - lat) * 10) / 10;

type Ring = [number, number][];
const land = (await (await fetch(LAND)).json()) as {
  features: { geometry: { coordinates: Ring[] } }[];
};
const rings = land.features
  .flatMap((feature) => feature.geometry.coordinates)
  .filter((ring) => Math.max(...ring.map(([, lat]) => lat)) > -60);
const path = rings
  .map(
    (ring) => `M${ring.map(([lon, lat]) => `${x(lon)} ${y(lat)}`).join("L")}Z`,
  )
  .join("");
writeFileSync(
  "public/world.svg",
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 360 144" aria-hidden="true"><path fill="#2A3246" d="${path}"/></svg>\n`,
);

// "+4730+01905" is 47°30' N, 19°05' E. Some have seconds too: "+353916+1394441".
function degrees(text: string, width: number): number {
  const sign = text[0] === "-" ? -1 : 1;
  const d = Number(text.slice(1, 1 + width));
  const m = Number(text.slice(1 + width, 3 + width));
  const s = Number(text.slice(3 + width) || 0);
  return sign * (d + m / 60 + s / 3600);
}

const places: Record<string, [number, number]> = {};
for (const line of readFileSync(ZONES, "utf8").split("\n")) {
  if (!line || line.startsWith("#")) continue;
  const [, coords, zone] = line.split("\t");
  const [, lat, lon] = /^([+-]\d+)([+-]\d+)$/.exec(coords) ?? [];
  places[zone] = [x(degrees(lon, 3)), y(degrees(lat, 2))];
}
writeFileSync(
  "src/zones.ts",
  `// Generated by scripts/world-map.ts from the tz database's zone.tab. Don't edit by hand.
// Each time zone's main city on the world map (x = longitude + 180, y = 84 - latitude).
export const PLACES: Record<string, [number, number]> = ${JSON.stringify(places)};
`,
);
console.log(
  `${rings.length} land shapes, ${Object.keys(places).length} time zones`,
);
